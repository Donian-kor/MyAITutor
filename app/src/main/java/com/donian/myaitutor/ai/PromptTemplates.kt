        """.trimIndent()

/** 수식이 필요 없는 과목이면 빈 문자열을 돌려줍니다. */
internal fun mathNotationInstruction(subject: String): String =
    if (subject in MATH_NOTATION_SUBJECTS) MATH_NOTATION_INSTRUCTION else ""

