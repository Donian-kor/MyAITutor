private val MATH_NOTATION_SUBJECTS = setOf("수학", "과학")

/** 수학·과학에서 사용하는 LaTeX 수식 표기 지침. */
private val MATH_NOTATION_INSTRUCTION: String = """
            [수식 표기]
            수식은 실제 수학식으로 표시될 수 있도록 표준 LaTeX 문법으로 작성하세요.
